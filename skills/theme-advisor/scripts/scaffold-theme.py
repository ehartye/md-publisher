#!/usr/bin/env python
"""Materialize a custom md-publisher theme from a spec JSON.

Reads a single-theme spec (the same shape a built-in theme has in
themes/theme-spec.json) and writes a theme directory at
~/.md-publisher/themes/<slug>/ containing:

    style.css            - WeasyPrint stylesheet (palette + fonts substituted in)
    cover.css            - per-theme cover-page styling (palette + fonts)
    mermaid-config.json  - mmdc config (palette + fonts)
    spec.json            - canonical record. Input palette/fonts are normalized
                           to snake_case keys (ink_soft, accent_alt, code_bg,
                           code_text, table_stripe; serif/sans/mono/display)
                           so lib.theme_loader.Palette / Fonts can read them
                           directly when the DOCX pipeline runs.
    preview.html         - small static preview of typography + palette

Usage:
    scaffold-theme.py --spec /tmp/my-theme.json [--force]

Spec schema (minimum fields):

    {
      "slug": "my-corp-light",
      "name": "my-corp",
      "mode": "light",
      "displayName": "My Corp Light",
      "tagline": "Brand-aligned editorial.",
      "fonts": {
        "display": "Charter, Georgia, serif",
        "body":    "Charter, Georgia, serif",
        "sans":    "Inter, system-ui, sans-serif",
        "mono":    "JetBrains Mono, Consolas, monospace"
      },
      "palette": {
        "bg":         "#FFFFFF",
        "paper":      "#FFFFFF",
        "ink":        "#111111",
        "inkSoft":    "#555555",
        "accent":     "#005FCC",
        "accentSoft": "#E0EBF8",
        "rule":       "#DDDDDD",
        "codeBg":     "#F5F5F5",
        "codeText":   "#111111"
      },
      "mermaid": {
        "tagStyling": {
          "ingress":   {"fill":"...", "stroke":"...", "color":"...", "strokeWidth":2},
          "core":      {"fill":"...", "stroke":"...", "color":"...", "strokeWidth":1},
          "transform": {"fill":"...", "stroke":"...", "color":"...", "strokeWidth":1},
          "bridge":    {"fill":"...", "stroke":"...", "color":"...", "strokeWidth":1}
        },
        "fontFamily": "Inter, sans-serif",
        "lineColor":  "#555555"
      }
    }

By default refuses to overwrite an existing theme directory. Pass --force
to overwrite.
"""

