# Validation patterns for spec values that flow into style.css + preview.html.
# Substituted values land verbatim into HTML/CSS contexts; rejecting fishy
# input early prevents stylesheet/HTML injection from a hand-edited or
# third-party theme spec.
#   - hex colors: 3, 4, 6, or 8 hex digits with leading #.
#   - bare font names (post first_family()): ASCII letters/digits/space/
#     hyphen/underscore/dot. Covers "Source Han Sans CN", "JetBrains Mono",
#     "IBM Plex Mono", "Newsreader". Rejects values containing CSS/HTML
#     control characters (`;`, `{`, `}`, `<`, `>`, `"`, `'`, `\`, `/`).
_HEX_COLOR_RE = re.compile(r"^#[0-9A-Fa-f]{3,8}$")
_FONT_FAMILY_RE = re.compile(r"^[A-Za-z0-9 _\-.]+$")


def _validate_palette(palette: dict) -> None:
    """Reject palette entries that aren't well-formed hex colors.

    Raises SystemExit(2) with a clear error naming the offending field
    so a typo or malicious spec halts the scaffold before it writes any
    output.
    """
    for key, value in palette.items():
        if not isinstance(value, str) or not _HEX_COLOR_RE.match(value):
            sys.stderr.write(
                f"[scaffold-theme] palette.{key} not a valid hex color: "
                f"{value!r} (expected #RGB / #RGBA / #RRGGBB / #RRGGBBAA)\n"
            )
            raise SystemExit(2)


def _validate_font(label: str, family: str) -> None:
    """Reject font family values that contain HTML/CSS-meaningful chars."""
    if not isinstance(family, str) or not _FONT_FAMILY_RE.match(family):
        sys.stderr.write(
            f"[scaffold-theme] {label} not a valid bare family name: "
            f"{family!r} (expected letters/digits/space/-_./, no quotes)\n"
        )
        raise SystemExit(2)


