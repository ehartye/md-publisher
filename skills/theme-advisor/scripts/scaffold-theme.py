def substitute(template: str, values: dict) -> str:
    out = template
    for key, val in values.items():
        out = out.replace("{{" + key + "}}", str(val))
    return out


def first_family(stack: str) -> str:
    """'Charter, Georgia, serif' -> 'Charter'"""
    return stack.split(",")[0].strip().strip('"').strip("'")


