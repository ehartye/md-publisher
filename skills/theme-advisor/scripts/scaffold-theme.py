def _classdef_props(style: dict) -> str:
    """Render a tagStyling style dict into a mermaid classDef rhs string."""
    parts = []
    for k, v in style.items():
        if k == "strokeWidth":
            parts.append(f"stroke-width:{v}")
        elif k == "strokeDasharray":
            parts.append(f"stroke-dasharray:{v}")
        else:
            parts.append(f"{k}:{v}")
    return ",".join(parts)


def _render_mermaid_to_svg(mermaid_src: str, mermaid_config_path: Path,
                           build_dir: Path, mmdc_path: Path) -> str | None:
    """Render a mermaid source via mmdc; return SVG string, or None on failure.

    Failures (mmdc missing, render error, timeout) return None so the caller
    can fall back to embedding the source. Preview rendering is non-blocking —
    the theme files are still produced regardless.
    """
    import subprocess as _sp
    if not mmdc_path.exists():
        return None
    src_path = build_dir / "preview.mmd"
    out_path = build_dir / "preview.svg"
    src_path.write_text(mermaid_src, encoding="utf-8")
    try:
        _sp.run(
            ["node", str(mmdc_path),
             "-i", str(src_path), "-o", str(out_path),
             "-c", str(mermaid_config_path),
             "-b", "transparent"],
            check=True, capture_output=True, timeout=30,
        )
    except (_sp.CalledProcessError, _sp.TimeoutExpired, FileNotFoundError):
        return None
    if not out_path.exists():
        return None
    return out_path.read_text(encoding="utf-8")


def _render_preview_figure(mermaid_src: str, mermaid_config_path: Path,
                           build_dir: Path, mmdc_path: Path) -> str:
    """Render `mermaid_src` via mmdc; on failure, return a fallback HTML block."""
    svg = _render_mermaid_to_svg(mermaid_src, mermaid_config_path, build_dir, mmdc_path)
    if svg:
        # Strip any leading XML declaration; we're inlining
        return re.sub(r"^<\?xml[^>]*\?>\s*", "", svg)
    escaped = mermaid_src.replace("&", "&amp;").replace("<", "&lt;")
    return (
        f'<pre class="mermaid-source">{escaped}</pre>'
        f'<p class="mermaid-fallback-note">'
        f'(install runtime then re-scaffold to see live diagrams)</p>'
    )


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--spec", type=Path, required=True, help="path to spec JSON")
    p.add_argument("--force", action="store_true",
                   help="overwrite an existing theme directory")
    args = p.parse_args()

    if not args.spec.exists():
        sys.stderr.write(f"[scaffold-theme] spec not found: {args.spec}\n")
        return 2
    spec = json.loads(args.spec.read_text(encoding="utf-8"))

    # Required fields
    for field in ("slug", "fonts", "palette", "mermaid"):
        if field not in spec:
            sys.stderr.write(f"[scaffold-theme] spec missing required field: {field}\n")
            return 2

    slug = spec["slug"]
    target = USER_THEMES_DIR / slug

    if target.exists() and not args.force:
        sys.stderr.write(
            f"[scaffold-theme] theme already exists: {target}\n"
            "Use --force to overwrite, or pick a different slug.\n"
        )
        return 1

    target.mkdir(parents=True, exist_ok=True)

    palette = spec["palette"]
    fonts = spec["fonts"]

    # Required palette fields (no fallback): missing these would crash
    # the substitute calls below with KeyError mid-write.
    for required in ("bg", "ink", "accent"):
        if required not in palette:
            sys.stderr.write(
                f"[scaffold-theme] palette missing required field: {required}\n"
            )
            return 2

    # Validate every value flowing into HTML/CSS contexts. Rejects
    # injection-shaped strings (CSS/HTML control chars, non-hex colors)
    # before any output file is written.
    _validate_palette(palette)
    for key, default in (("display", "serif"), ("body", "serif"),
                         ("sans", "sans-serif"), ("mono", "monospace")):
        family = fonts.get(key, default)
        # The values that flow into output files are always passed through
        # first_family() (style.css uses raw stack but only its own
        # template; preview.html + spec.json use bare). Validate the bare
        # form to catch any injection chars before the stack-strip too.
        _validate_font(f"fonts.{key}", first_family(family))
    if "lineColor" in spec["mermaid"]:
        if not _HEX_COLOR_RE.match(str(spec["mermaid"]["lineColor"])):
            sys.stderr.write(
                f"[scaffold-theme] mermaid.lineColor not a hex color: "
                f"{spec['mermaid']['lineColor']!r}\n"
            )
            return 2

    line_color = spec["mermaid"].get("lineColor", palette.get("accent", "#555555"))
    mermaid_font = spec["mermaid"].get("fontFamily", fonts.get("sans", "sans-serif"))
    display_name = spec.get("displayName", slug)
    tagline = spec.get("tagline", "Custom md-publisher theme.")

    style_subs = {
        "display_name": display_name,
        "font_display": fonts.get("display", "serif"),
        "font_body":    fonts.get("body", "serif"),
        "font_sans":    fonts.get("sans", "sans-serif"),
        "font_mono":    fonts.get("mono", "monospace"),
        "bg":           palette["bg"],
        "paper":        palette.get("paper", palette["bg"]),
        "ink":          palette["ink"],
        "ink_soft":     palette.get("inkSoft", palette["ink"]),
        "accent":       palette["accent"],
        "accent_soft":  palette.get("accentSoft", palette["accent"]),
        "rule":         palette.get("rule", palette.get("inkSoft", "#cccccc")),
        "code_bg":      palette.get("codeBg", palette.get("paper", palette["bg"])),
        "code_text":    palette.get("codeText", palette["ink"]),
    }
    style_css = substitute(STYLE_CSS_TEMPLATE, style_subs)
    (target / "style.css").write_text(style_css, encoding="utf-8")

    cover_css = substitute(COVER_CSS_TEMPLATE, style_subs)
    (target / "cover.css").write_text(cover_css, encoding="utf-8")

    mermaid_subs = {
        **style_subs,
        "line_color": line_color,
        "mermaid_font": mermaid_font,
    }
    mermaid_cfg_str = substitute(json.dumps(MERMAID_CONFIG_TEMPLATE, indent=2), mermaid_subs)
    # Validate it round-trips through json (catches typos in templates)
    json.loads(mermaid_cfg_str)
    (target / "mermaid-config.json").write_text(mermaid_cfg_str, encoding="utf-8")

    # Spec.json — persist the input but normalize palette + fonts to the
    # snake_case keys lib.theme_loader.Palette/Fonts expects so DOCX output
    # honors brand palette/fonts without the CSS-extraction fallback.
    persisted = dict(spec)
    persisted["palette"] = {
        "bg":           palette["bg"],
        "paper":        palette.get("paper", palette["bg"]),
        "ink":          palette["ink"],
        "ink_soft":     palette.get("inkSoft", palette["ink"]),
        "accent":       palette["accent"],
        "accent_alt":   palette.get("accentSoft", palette["accent"]),
        "rule":         palette.get("rule", palette.get("inkSoft", palette["ink"])),
        "code_bg":      palette.get("codeBg", palette.get("paper", palette["bg"])),
        "code_text":    palette.get("codeText", palette["ink"]),
        "table_stripe": palette.get("tableStripe", palette.get("paper", palette["bg"])),
    }
    # Persist bare family names (not CSS stacks) — Word's <w:rFonts> + the
    # install-fonts skill's OS lookup both need a single resolvable family.
    # Input fonts.body/sans/mono/display are CSS stacks per the docstring;
    # first_family() drops everything after the first comma.
    body = fonts.get("body", fonts.get("display", "serif"))
    persisted["fonts"] = {
        "serif":   first_family(body),
        "sans":    first_family(fonts.get("sans", "sans-serif")),
        "mono":    first_family(fonts.get("mono", "monospace")),
        "display": first_family(fonts.get("display", body)),
    }
    (target / "spec.json").write_text(
        json.dumps(persisted, indent=2), encoding="utf-8"
    )

    # Preview HTML — renders three mermaid figures (flowchart, ER, class)
    # using mmdc so the author can verify diagram styling before publishing.
    # Falls back to source blocks if the mmdc runtime isn't bootstrapped.
    mmdc_path = (
        Path.home() / ".md-publisher" / "runtime" / "node_modules"
        / "@mermaid-js" / "mermaid-cli" / "src" / "cli.js"
    )
    build_dir = target / ".preview-build"
    build_dir.mkdir(exist_ok=True)
    mermaid_config_path = target / "mermaid-config.json"

    flowchart_src = substitute(PREVIEW_FLOWCHART, {
        "ingress_classdef":   _classdef_props(spec["mermaid"]["tagStyling"]["ingress"]),
        "core_classdef":      _classdef_props(spec["mermaid"]["tagStyling"]["core"]),
        "transform_classdef": _classdef_props(spec["mermaid"]["tagStyling"]["transform"]),
        "bridge_classdef":    _classdef_props(spec["mermaid"]["tagStyling"]["bridge"]),
    })
    flowchart_figure = _render_preview_figure(flowchart_src, mermaid_config_path, build_dir, mmdc_path)
    er_figure = _render_preview_figure(PREVIEW_ER, mermaid_config_path, build_dir, mmdc_path)
    class_figure = _render_preview_figure(PREVIEW_CLASS, mermaid_config_path, build_dir, mmdc_path)

    # Cleanup the build dir; failures here are non-fatal.
    import shutil
    try:
        shutil.rmtree(build_dir)
    except OSError:
        pass

    preview_subs = {
        **style_subs,
        "tagline": tagline,
        "font_body_first": first_family(body),
        "style_css_inline": style_css,
        "flowchart_figure": flowchart_figure,
        "er_figure":        er_figure,
        "class_figure":     class_figure,
    }
    preview_html = substitute(PREVIEW_HTML_TEMPLATE, preview_subs)
    (target / "preview.html").write_text(preview_html, encoding="utf-8")

    print(f"[scaffold-theme] wrote theme to: {target}")
    print(f"  style.css            ({len(style_css)} bytes)")
    print(f"  mermaid-config.json  ({len(mermaid_cfg_str)} bytes)")
    print(f"  spec.json")
    print(f"  preview.html         (open in a browser to see the theme)")
    return 0


